#!/usr/bin/env python3
"""f202: turn the upstream Anime4K v4.0.1 GLSL into HLSL pixel shaders.

Run from the repo root:

    python scripts/qa-sr-anime4k-gen.py

It reads `assets/anime4k/Anime4K_Restore_CNN_{M,S}.glsl` (unmodified upstream
files, MIT, see `assets/sr/anime4k/LICENSE`) and writes
`src/dcomp/shaders/anime4k_restore_{m,s}.hlsl`, one entry point per pass:

    ps0 .. psN   ->  `float4 ps0(float4 frag : SV_Position) : SV_Target`

The conversion is mechanical, and that is the point: the weight matrices are
copied as literals, never retyped. What changes:

  * `vec4`/`vec2`/`vec3`/`mat4`               -> HLSL vector types;
  * `mat4(a..p) * v`                          -> `mul4x(float4x4(a..p), v)`
    (GLSL `m * v` == HLSL `mul(v, m)`, see `mul4x` in the prologue; both fill
    the 16 literals in the same order, so no transpose is involved);
  * `<name>_texOff(vec2(x, y))`               -> `L(tex_<name>, ip + int2(x, y))`
  * `<name>_tex(<name>_pos)`                  -> `L(tex_<name>, ip)`
    (`L` is a clamped point load: mpv's hooks clamp to edge, and `Load` with the
    index clamped to `dims.xy` is the same tap);
  * `vec4 hook() { ... }`                     -> the entry point body, with
    `int2 ip` bound to the pixel.

Texture registers follow the file's own `//!BIND` order, which is what
`src/dcomp/enhance.rs` binds.
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "sr", "anime4k")
DST = os.path.join(ROOT, "src", "dcomp", "shaders")

PROLOGUE = """\
// GENERATED by scripts/qa-sr-anime4k-gen.py from {origin}
// Anime4K v4.0.1, Copyright (c) 2019-2021 bloc97, MIT (assets/anime4k/LICENSE).
// Do not edit by hand: rerun the generator instead.
//
// cbuffer dims.xy is the *inclusive* maximum pixel index (width-1, height-1).

cbuffer Dims : register(b0)
{{
    float4 dims;
}};

float4 L(Texture2D<float4> tex, int2 p)
{{
    return tex.Load(int3(clamp(p, int2(0, 0), int2((int)dims.x, (int)dims.y)), 0));
}}

// GLSL `m * v` is `mul(v, m)` in HLSL (both index the 16 literals column-first).
float4 mul4x(float4x4 m, float4 v)
{{
    return mul(v, m);
}}
"""

VEC = {
    "vec4": "float4",
    "vec3": "float3",
    "vec2": "float2",
}

# `mat4(<literals>) * <op>` -> `mul4x(float4x4(<literals>), <op>)`
MATMUL = re.compile(r"mat4\(([^()]*)\)\s*\*\s*([A-Za-z_][A-Za-z_0-9]*(?:\([^()]*\))?)")
TEXOFF = re.compile(r"([A-Za-z_][A-Za-z_0-9]*)_texOff\(\s*vec2\(([^()]*)\)\s*\)")
TEXAT = re.compile(r"([A-Za-z_][A-Za-z_0-9]*)_tex\(\s*([A-Za-z_][A-Za-z_0-9]*)_pos\s*\)")

HEADER = re.compile(r"^//!(DESC|HOOK|BIND|SAVE|WIDTH|HEIGHT|COMPONENTS|WHEN|FORMAT)\s*(.*)$")


def passes(text):
    """Split the file into its `//!DESC` blocks, keeping the code of each."""
    out, current = [], None
    for raw in text.splitlines():
        hit = HEADER.match(raw.strip())
        if hit and hit.group(1) == "DESC":
            if current:
                out.append(current)
            current = {"desc": hit.group(2).strip(), "binds": [], "code": []}
            continue
        if current is None:
            continue
        if hit:
            if hit.group(1) == "BIND":
                current["binds"].append(hit.group(2).strip())
            continue
        if raw.strip().startswith("//"):
            continue
        if raw.strip():
            current["code"].append(raw.rstrip())
    if current:
        out.append(current)
    return out


def convert(code, binds):
    code = "\n".join(code)

    # Texture taps first: the patterns are written in GLSL (`vec2(...)`).
    def tex_off(match):
        name, args = match.group(1), match.group(2)
        if name not in binds:
            raise SystemExit("unknown texture %r (binds=%r)" % (name, binds))
        parts = [part.strip() for part in args.split(",")]
        if len(parts) != 2:
            raise SystemExit("texOff with %d arguments: %r" % (len(parts), args))
        return "L(tex_%s, ip + int2((int)(%s), (int)(%s)))" % (name, parts[0], parts[1])

    def tex_at(match):
        name = match.group(1)
        if name not in binds:
            raise SystemExit("unknown texture %r (binds=%r)" % (name, binds))
        return "L(tex_%s, ip)" % name

    code = TEXOFF.sub(tex_off, code)
    code = TEXAT.sub(tex_at, code)
    for glsl, hlsl in VEC.items():
        code = re.sub(r"\b%s\b" % glsl, hlsl, code)
    code = MATMUL.sub(lambda m: "mul4x(float4x4(%s), %s)" % (m.group(1), m.group(2)), code)
    return code


def build(source_name, origin):
    path = os.path.join(SRC, source_name)
    with open(path, "r", encoding="utf-8") as handle:
        text = handle.read()
    found = passes(text)
    body = [PROLOGUE.format(origin="Anime4K v4.0.1 " + source_name)]
    textures = {}
    for index, item in enumerate(found):
        code = convert(item["code"], item["binds"])
        if "hook()" not in code:
            raise SystemExit("pass %d has no hook()" % index)
        # `vec4 hook() {` -> the entry point; the trailing `}` stays.
        code = code.replace(
            "float4 hook() {",
            "float4 ps%d(float4 frag : SV_Position) : SV_Target\n{\n    int2 ip = int2(frag.xy);"
            % index,
        )
        if "float4 ps%d(" % index not in code:
            raise SystemExit("pass %d: hook() not rewritten" % index)
        for slot, name in enumerate(item["binds"]):
            textures[name] = slot
        body.append("// ---- pass %d: %s (inputs %s)" % (
            index, item["desc"], " ".join("t%d=%s" % (s, n) for s, n in enumerate(item["binds"]))))
        body.append(code)
        body.append("")
    decl = ["// texture registers: %s" % " ".join("t%d=%s" % (s, n) for n, s in sorted(textures.items(), key=lambda kv: kv[1]))]
    for name, slot in sorted(textures.items(), key=lambda kv: kv[1]):
        decl.append("Texture2D<float4> tex_%s : register(t%d);" % (name, slot))
    body.insert(1, "\n".join(decl) + "\n")
    return "\n".join(body), len(found)


def main():
    os.makedirs(DST, exist_ok=True)
    total = 0
    for variant in ("M", "S"):
        source = "Anime4K_Restore_CNN_%s.glsl" % variant
        text, count = build(source, source)
        target = os.path.join(DST, "anime4k_restore_%s.hlsl" % variant.lower())
        with open(target, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text if text.endswith("\n") else text + "\n")
        total += count
        print("%s -> %s (%d passes, %d bytes)" % (
            source, os.path.relpath(target, ROOT), count, len(text)))
    print("total %d passes" % total)


if __name__ == "__main__":
    main()
